-- Check-ins (Story 3.2, FR-13, FR-14, AD-2, AD-4, AD-6, AD-8, AD-9, AD-11, AD-14, AD-16).
--
-- checkins holds one posted photo per row: the client generates the id, uploads both WebP
-- renditions to the private bucket `checkins` at {group_id}/{checkin_id}/{1080|360}.webp, then calls
-- post_checkin, which alone decides timing (received_at, counted_at, is_late) and which session
-- the check-in completes. No match stores an extra (session_id null) that never counts.
--
-- AD-4: private.session_status(session) and private.counted_checkins(membership_id, week_start)
-- are the only places that decide done and counted. Story 3.5 adds `missed`, Epic 5 `frozen` and
-- removed check-ins, by redefining them here in place, never with a second copy.
--
-- Today's reads are extended through them: get_today_items gains done_count, counted_today and
-- target_met (drop + create, because the row type changes; the old app version ignores the extra
-- columns), get_today_summary counts done and left from session_status. get_checkin_targets is the
-- camera's picker read.
--
-- Additive only: one new table, one bucket with its policies, new functions, and the two Today
-- reads replaced with a superset of their columns. The routines call now() unqualified on purpose.
-- With search_path = '' that is pg_catalog.now(); pgTAP re-points a function's search_path at
-- test_overrides inside its rolled-back transaction so tests.freeze_time moves the clock.

-- 1. Table
create table public.checkins (
  -- Generated by the client (AD-8), so a retried post can never create a second row.
  id uuid primary key,
  group_id uuid not null references public.groups (id) on delete cascade,
  user_id uuid not null references public.profiles (id),
  commitment_id uuid not null references public.commitments (id) on delete cascade,
  -- The session this check-in completes; null = an extra that never raises the count.
  session_id uuid null references public.sessions (id) on delete set null,
  -- The device clock at the shutter press.
  captured_at timestamptz not null,
  -- The server's clock when post_checkin ran.
  received_at timestamptz not null,
  -- received_at when the delay is at most 10 min, else captured_at. Session matching uses it.
  counted_at timestamptz not null,
  is_late boolean not null,
  -- Trimmed, 1 to 80 characters, or null.
  caption text null
    constraint checkins_caption_check
    check (pg_catalog.char_length(caption) between 1 and 80),
  -- Set when the 1080 rendition is pruned (Story 7.3); only the 360 copy remains.
  full_pruned_at timestamptz null,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now()
);

-- 2. Indexes. Only-once rules live in unique indexes (AD-18): a session is completed once.
create unique index checkins_one_per_session
  on public.checkins (session_id)
  where session_id is not null;

create index checkins_group_id_received_at_idx on public.checkins (group_id, received_at desc);
create index checkins_commitment_id_idx on public.checkins (commitment_id);
create index checkins_user_id_idx on public.checkins (user_id);

create trigger checkins_set_updated_at
  before update on public.checkins
  for each row execute function private.set_updated_at();

-- 3. Helpers

-- True while p_user_id has a current membership in p_group_id. Security definer, so policies can
-- ask about another member without reading memberships under the caller's RLS.
create or replace function private.is_current_member(p_group_id uuid, p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.memberships m
    where m.group_id = p_group_id
      and m.user_id = p_user_id
      and m.ended_at is null
  );
$$;

-- 4. Row level security: current members of the group read check-ins whose author is still a
--    current member there (a left or removed member's check-ins disappear at once). No client
--    writes: post_checkin is the only writer.
alter table public.checkins enable row level security;

create policy checkins_select_member
  on public.checkins
  for select
  to authenticated
  using (private.is_member(group_id) and private.is_current_member(group_id, user_id));

revoke all on table public.checkins from public, anon, authenticated;
grant select on table public.checkins to authenticated;

-- 5. AD-4 single-definition functions. Security invoker: called from the security_invoker Today
--    reads, they read checkins under the caller's RLS. They never read the clock.

-- A session is `done` when a counted check-in completes it, else `open`.
create or replace function private.session_status(s public.sessions)
returns text
language sql
stable
security invoker
set search_path = ''
as $$
  select case
    when exists (select 1 from public.checkins c where c.session_id = s.id) then 'done'
    else 'open'
  end;
$$;

-- The counted check-ins of a member week, one row each with its commitment (callers count per
-- commitment, per day).
create or replace function private.counted_checkins(p_membership_id uuid, p_week_start date)
returns table (commitment_id uuid, checkin_id uuid, session_id uuid, counted_at timestamptz)
language sql
stable
security invoker
set search_path = ''
as $$
  select c.commitment_id, c.id, c.session_id, c.counted_at
  from public.sessions s
  join public.checkins c on c.session_id = s.id
  where s.membership_id = p_membership_id
    and s.week_start = p_week_start;
$$;

-- What post_checkin returns besides the row: the commitment's counted check-ins and sessions in
-- the member week. post_checkin only (security definer caller); no grant.
create or replace function private.checkin_counts(p_commitment_id uuid, p_week_start date)
returns table (done_count integer, target integer)
language sql
stable
set search_path = ''
as $$
  select
    (select count(*)::integer
     from public.commitments c
     cross join lateral private.counted_checkins(c.membership_id, p_week_start) k
     where c.id = p_commitment_id
       and k.commitment_id = p_commitment_id),
    (select count(*)::integer
     from public.sessions s
     where s.commitment_id = p_commitment_id
       and s.week_start = p_week_start);
$$;

revoke execute on function private.is_current_member(uuid, uuid) from public, anon, authenticated;
revoke execute on function private.session_status(public.sessions) from public, anon, authenticated;
revoke execute on function private.counted_checkins(uuid, date) from public, anon, authenticated;
revoke execute on function private.checkin_counts(uuid, date) from public, anon, authenticated;
grant execute on function private.is_current_member(uuid, uuid) to authenticated;
grant execute on function private.session_status(public.sessions) to authenticated;
grant execute on function private.counted_checkins(uuid, date) to authenticated;

