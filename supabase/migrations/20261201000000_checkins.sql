-- The object path's group and check-in ids when it is exactly
-- {group_id}/{checkin_id}/{1080|360}.webp (lowercase UUIDs), else nulls.
create or replace function private.checkin_photo_path(p_name text)
returns table (group_id uuid, checkin_id uuid)
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p_name is not null and p_name ~ (
    '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/'
    || '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/(1080|360)\.webp$'
  ) then
    group_id := pg_catalog.split_part(p_name, '/', 1)::uuid;
    checkin_id := pg_catalog.split_part(p_name, '/', 2)::uuid;
  end if;
  return next;
end;
$$;

-- INSERT: a well-formed path in a group the caller is a current member of, for a check-in id that
-- has no row yet (definer: sees every row, including ones hidden from the caller).
create or replace function private.can_upload_checkin_photo(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select p.group_id is not null
       and private.is_member(p.group_id)
       and not exists (select 1 from public.checkins c where c.id = p.checkin_id)
     from private.checkin_photo_path(p_name) p),
    false
  );
$$;

-- SELECT: current members of the path's group read the photos of check-ins visible to them, and
-- the owner reads their own uploads (before the row exists, e.g. the upload's own response).
-- Story 3.4 serves these through signed URLs.
create or replace function private.can_read_checkin_photo(p_name text, p_owner_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select p.group_id is not null
       and private.is_member(p.group_id)
       and (
         p_owner_id = (select auth.uid())::text
         or exists (
           select 1
           from public.checkins c
           where c.id = p.checkin_id
             and c.group_id = p.group_id
             and private.is_current_member(c.group_id, c.user_id)
         )
       )
     from private.checkin_photo_path(p_name) p),
    false
  );
$$;

revoke execute on function private.checkin_photo_path(text) from public, anon, authenticated;
revoke execute on function private.can_upload_checkin_photo(text) from public, anon, authenticated;
revoke execute on function private.can_read_checkin_photo(text, text) from public, anon, authenticated;
grant execute on function private.can_upload_checkin_photo(text) to authenticated;
grant execute on function private.can_read_checkin_photo(text, text) to authenticated;

