-- 7. RPC: post a check-in (FR-13, FR-14, AD-8).
--    Checks in order: signed in; an existing id (the same caller and payload get the stored result
--    back with no writes and no window checks, anything else checkin_conflict); the caption
--    (invalid_caption); the capture time (bad_capture_time); the commitment's group membership
--    (not_member); the commitment itself (commitment_ended: gone, not the caller's current
--    membership's, not started or ended in the week containing counted_at, or a task of another
--    week); the group week's lock (week_locked); both renditions in Storage (photo_missing).
--    The week and zone are the member's at counted_at (private.member_current_week), never today's.
--    Posts to one commitment are serialized by its row lock, so two posts never take one session.
create or replace function public.post_checkin(
  p_id uuid,
  p_commitment_id uuid,
  p_captured_at timestamptz,
  p_caption text default null
)
returns table (
  checkin_id uuid,
  session_id uuid,
  counted boolean,
  is_late boolean,
  done_count integer,
  target integer
)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := auth.uid();
  v_caption text;
  v_existing public.checkins;
  v_c public.commitments;
  v_membership_id uuid;
  v_received timestamptz;
  v_counted timestamptz;
  v_tz text;
  v_week date;
  v_version public.commitment_versions;
  v_lock_at timestamptz;
  v_session_id uuid;
  v_is_late boolean;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if p_id is null or p_commitment_id is null or p_captured_at is null then
    raise exception 'invalid_checkin';
  end if;

  v_caption := nullif(pg_catalog.regexp_replace(p_caption, '^\s+|\s+$', '', 'g'), '');

  -- The commitment's lock first, so a concurrent post to it (same id or not) waits here.
  select c.* into v_c
  from public.commitments c
  where c.id = p_commitment_id
  for update;

  select ck.* into v_existing from public.checkins ck where ck.id = p_id;
  if found then
    if v_existing.user_id = v_uid
       and v_existing.commitment_id = p_commitment_id
       and v_existing.captured_at = p_captured_at
       and v_existing.caption is not distinct from v_caption then
      select w.week_start into v_week
      from private.member_current_week(v_existing.user_id, v_existing.counted_at) w;
      return query
      select v_existing.id, v_existing.session_id, v_existing.session_id is not null,
             v_existing.is_late, x.done_count, x.target
      from private.checkin_counts(v_existing.commitment_id, v_week) x;
      return;
    end if;
    raise exception 'checkin_conflict';
  end if;

  if v_caption is not null and pg_catalog.char_length(v_caption) > 80 then
    raise exception 'invalid_caption';
  end if;

  v_received := now();
  if p_captured_at > v_received + interval '1 minute' then
    raise exception 'bad_capture_time';
  end if;
  v_counted := case
    when v_received - p_captured_at <= interval '10 minutes' then v_received
    else p_captured_at
  end;

  if v_c.id is null then
    raise exception 'commitment_ended';
  end if;

  -- FOR SHARE: a leave or removal of this membership waits until the post is done.
  select m.id into v_membership_id
  from public.memberships m
  where m.group_id = v_c.group_id
    and m.user_id = v_uid
    and m.ended_at is null
  for share;

  if v_membership_id is null then
    raise exception 'not_member';
  end if;

  if v_c.user_id <> v_uid or v_c.membership_id <> v_membership_id then
    raise exception 'commitment_ended';
  end if;

  select w.week_start, w.time_zone into v_week, v_tz
  from private.member_current_week(v_uid, v_counted) w;

  if v_c.kind = 'task' then
    if not exists (
      select 1 from public.sessions s
      where s.commitment_id = v_c.id and s.week_start = v_week
    ) then
      raise exception 'commitment_ended';
    end if;
  else
    if v_c.ends_after_week_start is not null and v_c.ends_after_week_start < v_week then
      raise exception 'commitment_ended';
    end if;
    select cv.* into v_version
    from public.commitment_versions cv
    where cv.commitment_id = v_c.id
      and cv.effective_week_start <= v_week
    order by cv.effective_week_start desc
    limit 1;
    if v_version.id is null or (v_version.end_date is not null and v_version.end_date < v_week) then
      raise exception 'commitment_ended';
    end if;
  end if;

  select gw.lock_at into v_lock_at
  from public.group_weeks gw
  where gw.group_id = v_c.group_id and gw.week_start = v_week;
  if v_lock_at is null then
    v_lock_at := private.local_start(v_week + 10, private.group_time_zone(v_c.group_id, v_week));
  end if;
  if v_received >= v_lock_at then
    raise exception 'week_locked';
  end if;

  if (
    select count(distinct o.name)
    from storage.objects o
    where o.bucket_id = 'checkins'
      and o.owner_id = v_uid::text
      and o.name in (
        v_c.group_id::text || '/' || p_id::text || '/1080.webp',
        v_c.group_id::text || '/' || p_id::text || '/360.webp'
      )
  ) < 2 then
    raise exception 'photo_missing';
  end if;

  -- Session matching (FR-14): the commitment's session whose [starts_at, ends_at) contains
  -- counted_at and that is not done yet, ended or miss-stamped ones included. Times per week: at
  -- most one counted check-in per member-local day.
  if v_c.kind = 'commitment' and v_c.schedule_type = 'times_per_week'
     and exists (
       select 1
       from private.counted_checkins(v_c.membership_id, v_week) k
       where k.commitment_id = v_c.id
         and (k.counted_at at time zone v_tz)::date = (v_counted at time zone v_tz)::date
     ) then
    v_session_id := null;
  else
    select s.id into v_session_id
    from public.sessions s
    where s.commitment_id = v_c.id
      and s.starts_at <= v_counted
      and v_counted < s.ends_at
      and private.session_status(s) = 'open'
    order by s.slot
    limit 1;
  end if;

  v_is_late := v_received - p_captured_at > interval '10 minutes'
    or (p_captured_at at time zone v_tz)::date <> (v_received at time zone v_tz)::date;

  insert into public.checkins
    (id, group_id, user_id, commitment_id, session_id, captured_at, received_at, counted_at,
     is_late, caption)
  values
    (p_id, v_c.group_id, v_uid, v_c.id, v_session_id, p_captured_at, v_received, v_counted,
     v_is_late, v_caption);

  return query
  select p_id, v_session_id, v_session_id is not null, v_is_late, x.done_count, x.target
  from private.checkin_counts(v_c.id, v_week) x;
end;
$$;

revoke execute on function public.post_checkin(uuid, uuid, timestamptz, text) from public, anon;
grant execute on function public.post_checkin(uuid, uuid, timestamptz, text) to authenticated;

-- 8. Today's rows, with done_count, counted_today and target_met (from 20261130000000, the
--    lookup unchanged). counted keeps its meaning (counted this week) and equals done_count.
--    A row is done (sorted below open rows): fixed days counted today, a task or a times-per-week
--    commitment at its target.
drop function public.get_today_items(uuid);

create function public.get_today_items(p_group_id uuid)
returns table (
  commitment_id uuid,
  kind text,
  section text,
  preset_key text,
  custom_name text,
  activity_name text,
  name text,
  schedule_type text,
  days smallint[],
  target smallint,
  counted smallint,
  deadline date,
  starts_on date,
  can_delete boolean,
  done_count smallint,
  counted_today boolean,
  target_met boolean
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := auth.uid();
  v_membership_id uuid;
  v_tz text;
  v_week_start date;
  v_today date;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if not private.is_member(p_group_id) then
    raise exception 'not_member';
  end if;

  select m.id into v_membership_id
  from public.memberships m
  where m.group_id = p_group_id
    and m.user_id = v_uid
    and m.ended_at is null;

  select w.time_zone, w.week_start into v_tz, v_week_start
  from private.member_current_week(v_uid, now()) w;
  v_today := (now() at time zone v_tz)::date;

  return query
  with week_sessions as (
    select
      s.commitment_id as cid,
      count(*)::smallint as session_count,
      bool_or(s.ends_at > now()) as has_open,
      bool_or(s.slot = extract(isodow from v_today) and s.ends_at > now()) as has_open_today_slot,
      max(s.ends_at) as last_ends_at
    from public.sessions s
    where s.membership_id = v_membership_id
      and s.week_start = v_week_start
    group by s.commitment_id
  ),
  counted as (
    select
      k.commitment_id as cid,
      count(*)::smallint as done_count,
      bool_or((k.counted_at at time zone v_tz)::date = v_today) as counted_today
    from private.counted_checkins(v_membership_id, v_week_start) k
    group by k.commitment_id
  ),
  current_rows as (
    select
      c.id as cid,
      c.kind as c_kind,
      c.group_activity_id as ga_id,
      c.name as c_name,
      c.schedule_type as c_schedule_type,
      c.deadline as c_deadline,
      c.deadline_day_starts_at as c_deadline_day_starts_at,
      w.session_count as c_target,
      coalesce(k.done_count, 0::smallint) as c_counted,
      coalesce(k.counted_today, false) as c_counted_today,
      -- Member-local days from today through the local day of the last session end.
      (((w.last_ends_at - interval '1 microsecond') at time zone v_tz)::date - v_today + 1) as days_left,
      v_week_start as version_week
    from public.commitments c
    join week_sessions w on w.cid = c.id
    left join counted k on k.cid = c.id
    where c.group_id = p_group_id
      and c.membership_id = v_membership_id
      and w.has_open
      and (
        (c.kind = 'task' and c.deadline >= v_today)
        or (c.kind = 'commitment' and c.schedule_type = 'times_per_week')
        or (c.kind = 'commitment' and c.schedule_type = 'fixed_days' and w.has_open_today_slot)
      )
  ),
  placed as (
    select
      r.*,
      case
        when r.c_kind = 'task' and r.c_deadline = v_today then 'due_today'
        when r.c_kind = 'task' then 'this_week'
        when r.c_schedule_type = 'fixed_days' then 'due_today'
        when r.c_target - r.c_counted > 0 and r.c_target - r.c_counted >= r.days_left then 'due_today'
        else 'this_week'
      end as c_section,
      null::date as c_starts_on
    from current_rows r
  ),
  next_rows as (
    select
      c.id as cid,
      c.kind as c_kind,
      c.group_activity_id as ga_id,
      c.name as c_name,
      c.schedule_type as c_schedule_type,
      c.deadline as c_deadline,
      c.deadline_day_starts_at as c_deadline_day_starts_at,
      null::smallint as c_target,
      0::smallint as c_counted,
      false as c_counted_today,
      null::integer as days_left,
      f.first_week as version_week,
      'starts_next_week' as c_section,
      f.first_week as c_starts_on
    from public.commitments c
    cross join lateral (
      select min(cv.effective_week_start) as first_week
      from public.commitment_versions cv
      where cv.commitment_id = c.id
    ) f
    where c.group_id = p_group_id
      and c.membership_id = v_membership_id
      and c.kind = 'commitment'
      and f.first_week > v_week_start
      and private.commitment_is_active(c)
  ),
  all_rows as (
    select * from placed
    union all
    select * from next_rows
  ),
  judged as (
    select
      a.*,
      coalesce(a.c_target is not null and a.c_counted >= a.c_target, false) as c_target_met,
      case
        when a.c_section = 'starts_next_week' then false
        when a.c_kind = 'commitment' and a.c_schedule_type = 'fixed_days' then a.c_counted_today
        else coalesce(a.c_counted >= a.c_target, false)
      end as c_done
    from all_rows a
  )
  select
    a.cid,
    a.c_kind,
    a.c_section,
    ga.preset_key,
    ga.custom_name,
    coalesce(pa.name, ga.custom_name),
    a.c_name,
    a.c_schedule_type,
    v.days,
    case
      when a.c_section = 'starts_next_week' then v.target
      else a.c_target
    end,
    a.c_counted,
    a.c_deadline,
    a.c_starts_on,
    coalesce(a.c_kind = 'task' and now() < a.c_deadline_day_starts_at, false),
    a.c_counted,
    a.c_counted_today,
    a.c_target_met
  from judged a
  join public.group_activities ga on ga.id = a.ga_id
  left join public.preset_activities pa on pa.key = ga.preset_key
  left join lateral (
    select cv.days, cv.target
    from public.commitment_versions cv
    where cv.commitment_id = a.cid
      and cv.effective_week_start <= a.version_week
    order by cv.effective_week_start desc
    limit 1
  ) v on true
  order by
    case a.c_section when 'due_today' then 0 when 'this_week' then 1 else 2 end,
    -- Open before done.
    a.c_done,
    case
      when a.c_kind = 'commitment' and a.c_schedule_type = 'fixed_days' then 0
      when a.c_kind = 'commitment' then 1
      else 2
    end,
    a.c_deadline nulls first,
    pg_catalog.lower(coalesce(a.c_name, pa.name, ga.custom_name)),
    a.cid;
end;
$$;

revoke execute on function public.get_today_items(uuid) from public, anon;
grant execute on function public.get_today_items(uuid) to authenticated;

-- 9. Today's summary: done and left from session_status (from 20261130000000, otherwise unchanged).
create or replace function public.get_today_summary(p_group_id uuid)
returns table (
  member_today date,
  week_start date,
  week_number integer,
  planned integer,
  done integer,
  "left" integer,
  has_plan boolean
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := auth.uid();
  v_tz text;
  v_week_start date;
  v_today date;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if not private.is_member(p_group_id) then
    raise exception 'not_member';
  end if;

  select w.time_zone, w.week_start into v_tz, v_week_start
  from private.member_current_week(v_uid, now()) w;
  v_today := (now() at time zone v_tz)::date;

  return query
  select
    v_today,
    v_week_start,
    greatest(1, (v_week_start - private.week_start_of(m.joined_at, v_tz)) / 7 + 1)::integer,
    x.planned,
    x.done,
    x.open_not_counted,
    exists (
      select 1
      from public.commitments c
      where c.membership_id = m.id
        and (
          (c.kind = 'commitment' and private.commitment_is_active(c))
          or (c.kind = 'task' and c.deadline >= v_today)
        )
    )
  from public.memberships m
  cross join lateral (
    select
      count(*)::integer as planned,
      (count(*) filter (where private.session_status(s) = 'done'))::integer as done,
      -- Open sessions not done yet.
      (count(*) filter (where s.ends_at > now() and private.session_status(s) = 'open'))::integer
        as open_not_counted
    from public.sessions s
    where s.membership_id = m.id
      and s.week_start = v_week_start
  ) x
  where m.group_id = p_group_id
    and m.user_id = v_uid
    and m.ended_at is null;
end;
$$;

revoke execute on function public.get_today_summary(uuid) from public, anon;
grant execute on function public.get_today_summary(uuid) to authenticated;

-- 10. RPC: the camera's picker (snap-first). The caller's commitments with sessions this week and
--     tasks due today or later, Today's due-today rows first (Today's own placement and order,
--     through get_today_items), then the rest. wont_count says why a post now would be an extra:
--     `not_today` (no session open right now: a fixed day not scheduled today, or a
--     times-per-week week cut short), `target_met` (times per week), `counted_today` (times per
--     week, or a fixed day already done today), `done` (a task), else null.
create or replace function public.get_checkin_targets(p_group_id uuid)
returns table (
  commitment_id uuid,
  kind text,
  preset_key text,
  custom_name text,
  activity_name text,
  name text,
  schedule_type text,
  due_today boolean,
  member_today date,
  deadline date,
  target smallint,
  done_count smallint,
  wont_count text
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := auth.uid();
  v_membership_id uuid;
  v_tz text;
  v_week_start date;
  v_today date;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if not private.is_member(p_group_id) then
    raise exception 'not_member';
  end if;

  select m.id into v_membership_id
  from public.memberships m
  where m.group_id = p_group_id
    and m.user_id = v_uid
    and m.ended_at is null;

  select w.time_zone, w.week_start into v_tz, v_week_start
  from private.member_current_week(v_uid, now()) w;
  v_today := (now() at time zone v_tz)::date;

  return query
  with week_sessions as (
    select
      s.commitment_id as cid,
      count(*)::smallint as session_count,
      bool_or(s.starts_at <= now() and now() < s.ends_at) as open_now,
      bool_or(s.starts_at <= now() and now() < s.ends_at and private.session_status(s) = 'open')
        as open_now_undone
    from public.sessions s
    where s.membership_id = v_membership_id
      and s.week_start = v_week_start
    group by s.commitment_id
  ),
  counted as (
    select
      k.commitment_id as cid,
      count(*)::smallint as done_count,
      bool_or((k.counted_at at time zone v_tz)::date = v_today) as counted_today
    from private.counted_checkins(v_membership_id, v_week_start) k
    group by k.commitment_id
  ),
  today_rows as (
    select t.commitment_id as cid, t.section as t_section, t.ord as t_ord
    from public.get_today_items(p_group_id) with ordinality
      as t(commitment_id, kind, section, preset_key, custom_name, activity_name, name,
           schedule_type, days, target, counted, deadline, starts_on, can_delete, done_count,
           counted_today, target_met, ord)
    where t.section <> 'starts_next_week'
  ),
  candidates as (
    select
      c.id as cid,
      c.kind as c_kind,
      c.group_activity_id as ga_id,
      c.name as c_name,
      c.schedule_type as c_schedule_type,
      c.deadline as c_deadline,
      w.session_count as c_target,
      coalesce(k.done_count, 0::smallint) as c_done,
      coalesce(k.counted_today, false) as c_counted_today,
      w.open_now,
      w.open_now_undone,
      t.t_section,
      t.t_ord
    from public.commitments c
    join week_sessions w on w.cid = c.id
    left join counted k on k.cid = c.id
    left join today_rows t on t.cid = c.id
    where c.group_id = p_group_id
      and c.membership_id = v_membership_id
      and (c.kind = 'commitment' or c.deadline >= v_today)
  )
  select
    r.cid,
    r.c_kind,
    ga.preset_key,
    ga.custom_name,
    coalesce(pa.name, ga.custom_name),
    r.c_name,
    r.c_schedule_type,
    coalesce(r.t_section = 'due_today', false),
    v_today,
    r.c_deadline,
    r.c_target,
    r.c_done,
    case
      when r.c_kind = 'task' then
        case when r.c_done >= r.c_target then 'done' end
      when not r.open_now then 'not_today'
      when r.c_schedule_type = 'times_per_week' and r.c_done >= r.c_target then 'target_met'
      when r.c_schedule_type = 'times_per_week' and r.c_counted_today then 'counted_today'
      when not r.open_now_undone then 'counted_today'
    end
  from candidates r
  join public.group_activities ga on ga.id = r.ga_id
  left join public.preset_activities pa on pa.key = ga.preset_key
  order by
    case r.t_section when 'due_today' then 0 when 'this_week' then 1 else 2 end,
    r.t_ord nulls last,
    case
      when r.c_kind = 'commitment' and r.c_schedule_type = 'fixed_days' then 0
      when r.c_kind = 'commitment' then 1
      else 2
    end,
    pg_catalog.lower(coalesce(r.c_name, pa.name, ga.custom_name)),
    r.cid;
end;
$$;

revoke execute on function public.get_checkin_targets(uuid) from public, anon;
grant execute on function public.get_checkin_targets(uuid) to authenticated;
